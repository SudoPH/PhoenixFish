    public enum TargetType { ANY, ANY_RARITY, FISH_ID, WEIGHT_MILESTONE }

    public record Range(int min, int max) {
        public int roll() {
            return min >= max ? min : ThreadLocalRandom.current().nextInt(min, max + 1);
        }
    }

    public record ItemReward(Material material, int amount) {}

    public record ContractTemplate(
            String id,
            String displayName,
            List<String> description,
            TargetType targetType,
            String targetValue,
            Range amountRange,
            Range moneyRange,
            Range xpRange,
            List<ItemReward> itemRewards,
            Material iconMaterial,
            int iconCmd
    ) {
        public String targetLabel() {
            return switch (targetType) {
                case ANY -> "any fish";
                case ANY_RARITY -> "any " + targetValue.toLowerCase();
                case FISH_ID -> targetValue;
                case WEIGHT_MILESTONE -> "fish ≥ " + targetValue + " kg";
            };
        }
    }

    /**
     * Per-player rolled contract instance. Immutable; progress + claim
     * mutations return new instances.
     */
    public record Contract(
            String templateId,
            String displayName,
            List<String> description,
            TargetType targetType,
            String targetValue,
            int amountNeeded,
            int amountCaught,
            double rewardMoney,
            int rewardXp,
            List<ItemReward> rewardItems,
            Material iconMaterial,
            int iconCmd,
            boolean claimed
    ) {
        public boolean isCompleted() { return amountCaught >= amountNeeded; }

        public Contract withCatch(int n) {
            int newCaught = Math.min(amountNeeded, amountCaught + n);
            return new Contract(templateId, displayName, description, targetType, targetValue,
                    amountNeeded, newCaught, rewardMoney, rewardXp, rewardItems,
                    iconMaterial, iconCmd, claimed);
        }

        public Contract markClaimed() {
            return new Contract(templateId, displayName, description, targetType, targetValue,
                    amountNeeded, amountCaught, rewardMoney, rewardXp, rewardItems,
                    iconMaterial, iconCmd, true);
        }
    }

