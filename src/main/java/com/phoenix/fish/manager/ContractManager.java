    public void openGUI(Player player) {
        if (!enabled) {
            player.sendMessage(miniMessage.deserialize("<red>Contract system is disabled."));
            return;
        }
        checkDailyReset(player);
        List<Contract> contracts = activeContracts.getOrDefault(player.getUniqueId(), Collections.emptyList());

        Inventory inv = Bukkit.createInventory(new ContractGUIHolder(), guiSize,
                miniMessage.deserialize(guiTitle));

        // Fill all slots with the filler item first.
        ItemStack filler = buildFiller();
        for (int i = 0; i < guiSize; i++) {
            inv.setItem(i, filler);
        }

        // Place each contract in its configured slot.
        for (int i = 0; i < contracts.size() && i < guiSlots.length; i++) {
            inv.setItem(guiSlots[i], buildContractItem(contracts.get(i)));
        }

        player.openInventory(inv);
    }

    private ItemStack buildFiller() {
        ItemStack item = new ItemStack(fillerMaterial);
        ItemMeta meta = item.getItemMeta();
        if (meta != null) {
            meta.displayName(miniMessage.deserialize(fillerName));
            meta.addItemFlags(org.bukkit.inventory.ItemFlag.values());
            item.setItemMeta(meta);
        }
        return item;
    }

    private ItemStack buildContractItem(Contract c) {
        boolean done = c.isCompleted();
        boolean claimed = c.claimed();
        Material mat = claimed ? iconClaimed : (done ? iconClaimable : iconActive);

        ItemStack item = new ItemStack(mat);
        ItemMeta meta = item.getItemMeta();
        if (meta == null) return item;

        // Display name — color reflects state.
        String nameColor = claimed ? "<green>" : (done ? "<green><bold>" : "<yellow>");
        String closeBold = done && !claimed ? "</bold>" : "";
        meta.displayName(miniMessage.deserialize(nameColor + c.displayName() + closeBold));

        List<net.kyori.adventure.text.Component> lore = new ArrayList<>();

        // v1.7.2 — Description lines (template-provided).
        // Filter out lines that look like reward summaries — the auto-generated
        // "Rewards:" block below is the single source of reward info, so any
        // description line that contains both a money pattern ($<digits>) and
        // an XP pattern (<digits> XP) would duplicate the display.
        // This filter is defensive: bundled templates no longer include reward
        // lines, but user-customized templates might. The regex matches both
        // substituted ("$500 + 50 XP") and unsubstituted ("$%money% + %xp% XP") forms.
        java.util.regex.Pattern rewardLinePattern = java.util.regex.Pattern.compile(
                "\\$[%\\d.,]+.*?\\d+\\s*XP|\\$%money%.*?%xp%\\s*XP",
                java.util.regex.Pattern.CASE_INSENSITIVE);
        for (String line : c.description()) {
            if (rewardLinePattern.matcher(line).find()) continue;
            lore.add(miniMessage.deserialize(line));
        }
        lore.add(miniMessage.deserialize("<dark_gray>───────────────"));

        // Objective + progress.
        String targetLine = "<gray>Target: <white>" + humanTarget(c) + " <dark_gray>(";
        targetLine += switch (c.targetType()) {
            case ANY -> "any fish";
            case ANY_RARITY -> "rarity: " + c.targetValue().toLowerCase();
            case FISH_ID -> "specific fish";
            case WEIGHT_MILESTONE -> "weight ≥ " + c.targetValue() + " kg";
        };
        targetLine += ")";
        lore.add(miniMessage.deserialize(targetLine));

        String progressColor = done ? "<green>" : "<yellow>";
        String progressLine = "<gray>Progress: " + progressColor + c.amountCaught()
                + "<gray>/<white>" + c.amountNeeded();
        if (done && !claimed) progressLine += " <green>✔";
        if (claimed) progressLine += " <dark_gray>(claimed)";
        lore.add(miniMessage.deserialize(progressLine));

        // Rewards block.
        lore.add(miniMessage.deserialize("<dark_gray>───────────────"));
        lore.add(miniMessage.deserialize("<gray>Rewards:"));
        if (c.rewardMoney() > 0) {
            lore.add(miniMessage.deserialize(" <dark_gray>• <gold>$"
                    + String.format("%.2f", c.rewardMoney())));
        }
        if (c.rewardXp() > 0) {
            lore.add(miniMessage.deserialize(" <dark_gray>• <aqua>" + c.rewardXp() + " XP"));
        }
        for (ItemReward ir : c.rewardItems()) {
            lore.add(miniMessage.deserialize(" <dark_gray>• <white>"
                    + ir.amount() + "x " + prettifyMaterial(ir.material())));
        }

        // State prompt — the "claim" hint is what makes the click affordance discoverable.
        if (done && !claimed) {
            lore.add(miniMessage.deserialize("<dark_gray>───────────────"));
            lore.add(miniMessage.deserialize("<green><bold>► Click to Claim!</bold></green>"));
        } else if (claimed) {
            lore.add(miniMessage.deserialize("<dark_gray>───────────────"));
            lore.add(miniMessage.deserialize("<dark_gray>✔ Reward already claimed"));
        }

        // Custom model data for the icon (only set if non-zero — 0 is the
        // vanilla default and overriding it would clear any resource-pack CMD).
        if (c.iconCmd() != 0) {
            meta.setCustomModelData(c.iconCmd());
        }

        meta.lore(lore);
        meta.addItemFlags(org.bukkit.inventory.ItemFlag.values());
        item.setItemMeta(meta);
        return item;
    }

    private String humanTarget(Contract c) {
        return switch (c.targetType()) {
            case ANY -> "Any Fish";
            case ANY_RARITY -> "Any " + capitalize(c.targetValue()) + " Fish";
            case FISH_ID -> c.targetValue();
            case WEIGHT_MILESTONE -> "Fish ≥ " + c.targetValue() + " kg";
        };
    }

    private String prettifyMaterial(Material m) {
        String[] parts = m.name().toLowerCase(Locale.ROOT).replace('_', ' ').split(" ");
        StringBuilder sb = new StringBuilder();
        for (String p : parts) {
            if (sb.length() > 0) sb.append(' ');
            sb.append(Character.toUpperCase(p.charAt(0))).append(p.substring(1));
        }
        return sb.toString();
    }

    private String capitalize(String s) {
        if (s == null || s.isEmpty()) return s;
        return Character.toUpperCase(s.charAt(0)) + s.substring(1).toLowerCase(Locale.ROOT);
    }

