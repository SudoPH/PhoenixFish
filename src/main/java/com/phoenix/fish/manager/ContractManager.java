    private File getTemplateFile() {
        return new File(plugin.getDataFolder(), "contract_templates.yml");
    }

    private File getPlayerDataFile() {
        return new File(plugin.getDataFolder(), "contracts.yml");
    }

    private void loadConfig() {
        // Try the dedicated template file first; fall back to legacy
        // features.contracts block in config.yml for backward compat.
        YamlConfiguration cfg;
        File f = getTemplateFile();
        if (f.exists()) {
            cfg = YamlConfiguration.loadConfiguration(f);
        } else {
            cfg = new YamlConfiguration();
        }

        boolean templateEnabled = cfg.getBoolean("settings.enabled", true);
        boolean legacyEnabled = plugin.getConfig().getBoolean("features.contracts.enabled", false);
        this.enabled = templateEnabled && (legacyEnabled || f.exists());

        this.dailyContractCount = cfg.getInt("settings.daily-contract-count",
                plugin.getConfig().getInt("features.contracts.daily-contract-count", 3));
        this.poolRollSize = cfg.getInt("settings.pool-roll-size", 5);
        this.resetHour = cfg.getInt("settings.reset-hour",
                plugin.getConfig().getInt("features.contracts.reset-hour", 0));
        this.announceOnReset = cfg.getBoolean("settings.announce-on-reset", true);
        this.autoGenerateDefaults = cfg.getBoolean("settings.auto-generate-defaults", true);

        // GUI config (with sensible defaults)
        ConfigurationSection guiSec = cfg.getConfigurationSection("settings.gui");
        this.guiTitle = guiSec != null ? guiSec.getString("title",
                "<dark_gray>» <gold><bold>Daily Contracts</bold></gold>") : "<dark_gray>» <gold>Daily Contracts";
        this.guiSize = guiSec != null ? guiSec.getInt("size", 27) : 27;
        if (this.guiSize < 9 || this.guiSize % 9 != 0) this.guiSize = 27;

        ConfigurationSection fillerSec = guiSec != null ? guiSec.getConfigurationSection("filler") : null;
        this.fillerMaterial = parseMaterial(
                fillerSec != null ? fillerSec.getString("material", "GRAY_STAINED_GLASS_PANE") : "GRAY_STAINED_GLASS_PANE",
                Material.GRAY_STAINED_GLASS_PANE);
        this.fillerName = fillerSec != null ? fillerSec.getString("name", " ") : " ";

        List<Integer> slots = guiSec != null ? guiSec.getIntegerList("slots") : Collections.emptyList();
        if (slots.isEmpty()) slots = Arrays.asList(10, 12, 14, 16, 22);
        this.guiSlots = slots.stream().mapToInt(Integer::intValue).toArray();

        ConfigurationSection iconsSec = guiSec != null ? guiSec.getConfigurationSection("icons") : null;
        this.iconActive = parseMaterial(
                iconsSec != null ? iconsSec.getString("active", "PAPER") : "PAPER", Material.PAPER);
        this.iconClaimable = parseMaterial(
                iconsSec != null ? iconsSec.getString("completed-claimable", "LIME_CONCRETE") : "LIME_CONCRETE",
                Material.LIME_CONCRETE);
        this.iconClaimed = parseMaterial(
                iconsSec != null ? iconsSec.getString("completed-claimed", "GREEN_STAINED_GLASS") : "GREEN_STAINED_GLASS",
                Material.GREEN_STAINED_GLASS);
    }

    private void loadTemplates() {
        templates.clear();
        File f = getTemplateFile();
        if (!f.exists()) {
            // Don't warn here — the constructor's auto-generation block
            // handles missing files. Just return empty and let the caller
            // decide what to do.
            return;
        }
        YamlConfiguration cfg = YamlConfiguration.loadConfiguration(f);
        ConfigurationSection sec = cfg.getConfigurationSection("templates");
        if (sec == null) {
            plugin.getLogger().warning("No 'templates:' section in contract_templates.yml.");
            return;
        }
        for (String id : sec.getKeys(false)) {
            ConfigurationSection tSec = sec.getConfigurationSection(id);
            if (tSec == null) continue;
            try {
                ContractTemplate t = parseTemplate(id, tSec);
                if (t != null) templates.put(id, t);
            } catch (Exception e) {
                plugin.getLogger().warning("Failed to parse contract template '" + id + "': " + e.getMessage());
            }
        }
    }

    /**
     * v1.7.1 — Auto-generation / fallback mechanism.
     *
     * <p>If the data-folder {@code contract_templates.yml} does not exist OR
     * exists but has an empty {@code templates:} section, this method
     * extracts the bundled jar resource of the same name into the data
     * folder. Subsequent {@link #loadTemplates()} calls will then pick up
     * the restored defaults.</p>
     *
     * <p>Defense-in-depth: if the jar doesn't ship the resource either,
     * the constructor falls back to {@link BuiltinDefaults#TEMPLATES} —
     * an in-memory hardcoded pool. The GUI never renders empty.</p>
     */
    private void ensureDefaultFile() {
        File f = getTemplateFile();
        try {
            if (!f.exists()) {
                // Extract bundled resource (replace=false is intentional —
                // but the file is missing anyway, so write always happens).
                plugin.saveResource("contract_templates.yml", false);
                plugin.getLogger().info("ContractManager: extracted default "
                        + "contract_templates.yml to data folder.");
                return;
            }
            // File exists but templates section was empty (user deleted
            // everything). Overwrite with defaults ONCE — but only if the
            // jar actually has the resource, otherwise we'd be writing
            // an empty file.
            if (plugin.getResource("contract_templates.yml") == null) {
                plugin.getLogger().warning("ContractManager: bundled default "
                        + "contract_templates.yml missing from jar — cannot "
                        + "restore defaults to disk. Falling back to in-memory "
                        + "pool only.");
                return;
            }
            // Back up the user's broken file before overwriting, so they
            // can recover any partial edits.
            File backup = new File(plugin.getDataFolder(),
                    "contract_templates.yml.broken-" + System.currentTimeMillis());
            try {
                java.nio.file.Files.move(f.toPath(), backup.toPath(),
                        java.nio.file.StandardCopyOption.REPLACE_EXISTING);
            } catch (IOException ignored) { }
            plugin.saveResource("contract_templates.yml", true);
            plugin.getLogger().warning("ContractManager: contract_templates.yml "
                    + "had empty templates section — restored defaults. "
                    + "Previous file backed up as " + backup.getName() + ".");
        } catch (IllegalArgumentException e) {
            plugin.getLogger().severe("ContractManager: failed to extract "
                    + "default contract_templates.yml: " + e.getMessage());
        }
    }

    private ContractTemplate parseTemplate(String id, ConfigurationSection s) {
        String displayName = s.getString("display-name", "<yellow>" + id);
        List<String> description = s.getStringList("description");
        if (description.isEmpty()) description = Collections.singletonList("<gray>(no description)");

        ConfigurationSection targetSec = s.getConfigurationSection("target");
        if (targetSec == null) {
            plugin.getLogger().warning("Template '" + id + "' missing 'target:' block — skipped.");
            return null;
        }
        TargetType tType;
        try {
            tType = TargetType.valueOf(targetSec.getString("type", "ANY").trim().toUpperCase(Locale.ROOT));
        } catch (IllegalArgumentException e) {
            plugin.getLogger().warning("Template '" + id + "' has invalid target type '"
                    + targetSec.getString("type") + "' — skipped.");
            return null;
        }
        String tValue = targetSec.getString("value", "").trim();

        Range amount = parseRange(s, "amount", 1, 1);
        ConfigurationSection rewardsSec = s.getConfigurationSection("rewards");
        Range money = parseRange(rewardsSec, "money", 0, 0);
        Range xp = parseRange(rewardsSec, "xp", 0, 0);
        List<ItemReward> items = new ArrayList<>();
        if (rewardsSec != null && rewardsSec.isList("items")) {
            for (Map<?, ?> m : rewardsSec.getMapList("items")) {
                Material mat = parseMaterial(String.valueOf(m.get("material")), Material.AIR);
                if (mat == Material.AIR) continue;
                Object amtObj = m.get("amount");
                int amt = (amtObj instanceof Number) ? ((Number) amtObj).intValue() : 1;
                items.add(new ItemReward(mat, Math.max(1, amt)));
            }
        }

        ConfigurationSection iconSec = s.getConfigurationSection("icon");
        Material iconMat = parseMaterial(
                iconSec != null ? iconSec.getString("material", "PAPER") : "PAPER", Material.PAPER);
        int iconCmd = iconSec != null ? iconSec.getInt("custom-model-data", 0) : 0;

        return new ContractTemplate(id, displayName, description, tType, tValue,
                amount, money, xp, items, iconMat, iconCmd);
    }

    /**
     * Parse a min-max range from a parent section's child key. Supports
     * four YAML forms:
     *   1. amount: { min: 5, max: 10 }   (Bukkit exposes as ConfigurationSection)
     *   2. amount: { min: 5, max: 10 }   (Bukkit exposes as Map in some contexts)
     *   3. amount: 5                      (scalar — min==max==5)
     *   4. amount: "5-10"                 (range string)
     */
    private Range parseRange(ConfigurationSection parent, String key, int defMin, int defMax) {
        if (parent == null) return new Range(defMin, defMax);
        Object raw = parent.get(key);
        if (raw == null) return new Range(defMin, defMax);

        if (raw instanceof Number n) {
            int v = n.intValue();
            return new Range(v, v);
        }
        if (raw instanceof Map<?, ?> m) {
            Object minO = m.get("min");
            Object maxO = m.get("max");
            int min = (minO instanceof Number) ? ((Number) minO).intValue() : defMin;
            int max = (maxO instanceof Number) ? ((Number) maxO).intValue() : defMax;
            if (min > max) { int t = min; min = max; max = t; }
            return new Range(min, max);
        }
        if (raw instanceof ConfigurationSection cs) {
            if (cs.contains("min") || cs.contains("max")) {
                int min = cs.getInt("min", defMin);
                int max = cs.getInt("max", defMax);
                if (min > max) { int t = min; min = max; max = t; }
                return new Range(min, max);
            }
            if (cs.isInt("value")) {
                int v = cs.getInt("value");
                return new Range(v, v);
            }
        }
        if (raw instanceof String s && s.contains("-")) {
            String[] parts = s.split("-", 2);
            try {
                int a = Integer.parseInt(parts[0].trim());
                int b = Integer.parseInt(parts[1].trim());
                if (a > b) { int t = a; a = b; b = t; }
                return new Range(a, b);
            } catch (NumberFormatException ignored) { }
        }
        return new Range(defMin, defMax);
    }

    private Material parseMaterial(String name, Material fallback) {
        if (name == null || name.isBlank()) return fallback;
        Material m = Material.matchMaterial(name.toUpperCase(Locale.ROOT));
        return m != null ? m : fallback;
    }

