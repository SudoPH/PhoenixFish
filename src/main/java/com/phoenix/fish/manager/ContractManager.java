    /**
     * Called by AchievementContractListener when a player clicks a contract
     * slot in the GUI. If the contract is completed but not yet claimed,
     * dispatch rewards and mark as claimed. Otherwise no-op.
     *
     * @return true if the inventory should be refreshed (a claim happened).
     */
    public boolean handleSlotClick(Player player, int slot) {
        if (!enabled || player == null) return false;
        UUID uuid = player.getUniqueId();
        List<Contract> contracts = activeContracts.get(uuid);
        if (contracts == null) return false;

        int contractIndex = slotToContractIndex(slot);
        if (contractIndex < 0 || contractIndex >= contracts.size()) return false;

        Contract c = contracts.get(contractIndex);
        if (!c.isCompleted() || c.claimed()) return false;

        // Dispatch rewards.
        if (c.rewardMoney() > 0) {
            var cache = plugin.getCacheManager();
            if (cache != null) {
                var data = cache.getData(uuid);
                if (data != null) data.addBalance(c.rewardMoney());
            }
        }
        if (c.rewardXp() > 0) {
            var cache = plugin.getCacheManager();
            if (cache != null) cache.addXpAndCheckLevel(player, c.rewardXp());
        }
        for (ItemReward ir : c.rewardItems()) {
            ItemStack stack = new ItemStack(ir.material(), Math.max(1, ir.amount()));
            Map<Integer, ItemStack> overflow = player.getInventory().addItem(stack);
            for (ItemStack drop : overflow.values()) {
                player.getWorld().dropItemNaturally(player.getLocation(), drop);
            }
        }

        contracts.set(contractIndex, c.markClaimed());
        dirty = true;

        player.sendMessage(miniMessage.deserialize(
                "<green><bold>✔ Reward Claimed!</bold></green> <white>"
                        + c.displayName() + " <dark_gray>— <gold>$"
                        + String.format("%.2f", c.rewardMoney()) + " <aqua>+ "
                        + c.rewardXp() + " XP"));
        player.playSound(player, org.bukkit.Sound.ENTITY_PLAYER_LEVELUP, 0.7f, 1.2f);
        return true;
    }

    /** Map a GUI slot index to a contract list index (or -1 if not a contract slot). */
    private int slotToContractIndex(int slot) {
        for (int i = 0; i < guiSlots.length; i++) {
            if (guiSlots[i] == slot) return i;
        }
        return -1;
    }

