    private void loadPlayerData() {
        File file = getPlayerDataFile();
        if (!file.exists()) return;
        YamlConfiguration cfg = YamlConfiguration.loadConfiguration(file);
        for (String uuidStr : cfg.getKeys(false)) {
            try {
                UUID uuid = UUID.fromString(uuidStr);
                ConfigurationSection playerSec = cfg.getConfigurationSection(uuidStr);
                if (playerSec == null) continue;
                lastResetDate.put(uuid, playerSec.getString("date", ""));
                List<Contract> contracts = new ArrayList<>();
                ConfigurationSection listSec = playerSec.getConfigurationSection("contracts");
                if (listSec != null) {
                    for (String key : listSec.getKeys(false)) {
                        ConfigurationSection cSec = listSec.getConfigurationSection(key);
                        if (cSec == null) continue;
                        ContractTemplate tpl = templates.get(cSec.getString("template", ""));
                        Contract c = deserializeContract(cSec, tpl);
                        if (c != null) contracts.add(c);
                    }
                }
                activeContracts.put(uuid, contracts);
            } catch (IllegalArgumentException ignored) { }
        }
    }

    /** Build a Contract from saved data. If the template still exists, use
     *  its current display-name/description/icon (so config edits propagate
     *  on next reload); otherwise fall back to persisted fields. */
    private Contract deserializeContract(ConfigurationSection s, ContractTemplate tpl) {
        String templateId = s.getString("template", "");
        TargetType tType;
        try {
            tType = TargetType.valueOf(s.getString("target-type", "ANY").toUpperCase(Locale.ROOT));
        } catch (IllegalArgumentException e) {
            tType = TargetType.ANY;
        }
        String tValue = s.getString("target-value", "");
        int needed = s.getInt("needed", 1);
        int caught = s.getInt("caught", 0);
        double money = s.getDouble("reward-money", 0);
        int xp = s.getInt("reward-xp", 0);
        boolean claimed = s.getBoolean("claimed", false);

        List<ItemReward> items = new ArrayList<>();
        for (Map<?, ?> m : s.getMapList("reward-items")) {
            Material mat = parseMaterial(String.valueOf(m.get("material")), Material.AIR);
            if (mat == Material.AIR) continue;
            Object amtObj = m.get("amount");
            int amt = (amtObj instanceof Number) ? ((Number) amtObj).intValue() : 1;
            items.add(new ItemReward(mat, Math.max(1, amt)));
        }

        if (tpl != null) {
            // v1.7.2 — FIX: previously used tpl.displayName() / tpl.description()
            // RAW, which left %amount% / %money% / %xp% unsubstituted on reload.
            // Now we substitute using the persisted rolled values so the GUI
            // shows the same numbers the player was assigned at daily reset.
            SubstitutedStrings sub = substitutePlaceholders(tpl, needed, money, xp);
            return new Contract(templateId, sub.displayName(), sub.description(),
                    tpl.targetType(), tpl.targetValue(), needed, caught, money, xp,
                    tpl.itemRewards(), tpl.iconMaterial(), tpl.iconCmd(), claimed);
        }
        // Template was removed from config — keep contract playable with persisted metadata.
        Material iconMat = parseMaterial(s.getString("icon-material", "PAPER"), Material.PAPER);
        int iconCmd = s.getInt("icon-cmd", 0);
        List<String> desc = s.getStringList("description");
        if (desc.isEmpty()) desc = Collections.singletonList("<gray>(legacy contract)");
        return new Contract(templateId, s.getString("display-name", templateId), desc,
                tType, tValue, needed, caught, money, xp, items, iconMat, iconCmd, claimed);
    }

    public synchronized void save() {
        if (!enabled) return;
        YamlConfiguration cfg = new YamlConfiguration();
        for (Map.Entry<UUID, List<Contract>> entry : activeContracts.entrySet()) {
            String uuidStr = entry.getKey().toString();
            cfg.set(uuidStr + ".date", lastResetDate.getOrDefault(entry.getKey(), ""));
            List<Contract> contracts = entry.getValue();
            for (int i = 0; i < contracts.size(); i++) {
                Contract c = contracts.get(i);
                String base = uuidStr + ".contracts." + i;
                cfg.set(base + ".template", c.templateId());
                cfg.set(base + ".display-name", c.displayName());
                cfg.set(base + ".description", c.description());
                cfg.set(base + ".target-type", c.targetType().name());
                cfg.set(base + ".target-value", c.targetValue());
                cfg.set(base + ".needed", c.amountNeeded());
                cfg.set(base + ".caught", c.amountCaught());
                cfg.set(base + ".reward-money", c.rewardMoney());
                cfg.set(base + ".reward-xp", c.rewardXp());
                cfg.set(base + ".claimed", c.claimed());
                cfg.set(base + ".icon-material", c.iconMaterial().name());
                cfg.set(base + ".icon-cmd", c.iconCmd());

                List<Map<String, Object>> items = new ArrayList<>();
                for (ItemReward ir : c.rewardItems()) {
                    items.add(Map.of("material", ir.material().name(), "amount", ir.amount()));
                }
                cfg.set(base + ".reward-items", items);
            }
        }
        try {
            cfg.save(getPlayerDataFile());
            dirty = false;
        } catch (IOException e) {
            plugin.getLogger().severe("Failed to save contracts.yml: " + e.getMessage());
        }
    }

    // =====================================================================
    //  Daily Reset + Assignment
    // =====================================================================

    private String getToday() {
        return java.time.LocalDate.now().toString();
    }

    public void checkDailyReset(Player player) {
        if (!enabled) return;
        UUID uuid = player.getUniqueId();
        String today = getToday();
        String lastDate = lastResetDate.get(uuid);

        if (!today.equals(lastDate)) {
            assignNewContracts(uuid);
            lastResetDate.put(uuid, today);
            dirty = true;
            if (announceOnReset) {
                player.sendMessage(miniMessage.deserialize(
                        "<gold><bold>★ New daily contracts assigned!</bold></gold> "
                                + "<gray>Use <yellow>/pf contracts</yellow> to view them."));
            }
        }
    }

    private void assignNewContracts(UUID uuid) {
        if (templates.isEmpty()) {
            plugin.getLogger().warning("ContractManager: template pool is empty — "
                    + "cannot assign contracts. Add templates to contract_templates.yml.");
            activeContracts.put(uuid, new ArrayList<>());
            return;
        }

        // Shuffle templates, take top pool-roll-size, then pick first daily-contract-count.
        List<ContractTemplate> shuffled = new ArrayList<>(templates.values());
        Collections.shuffle(shuffled);
        int poolSize = Math.min(poolRollSize, shuffled.size());
        int assignCount = Math.min(dailyContractCount, poolSize);

        List<Contract> newContracts = new ArrayList<>();
        for (int i = 0; i < assignCount; i++) {
            newContracts.add(rollContract(shuffled.get(i)));
        }
        activeContracts.put(uuid, newContracts);
    }

    /**
     * v1.7.2 — Single source of truth for placeholder substitution.
     * Replaces %amount%, %target%, %money%, %xp%, %value% in a template's
     * display-name and description lines using the supplied rolled values.
     * Used by both rollContract() (fresh daily assignment) and
     * deserializeContract() (reload from saved data) — guarantees identical
     * substitution behavior on both paths.
     */
    private record SubstitutedStrings(String displayName, List<String> description) {}

    private SubstitutedStrings substitutePlaceholders(ContractTemplate tpl,
                                                      int amount, double money, int xp) {
        String amountStr = String.valueOf(amount);
        String moneyStr = String.format("%.0f", money);
        String xpStr = String.valueOf(xp);
        String targetStr = tpl.targetLabel();
        String valueStr = tpl.targetValue();

        String display = tpl.displayName()
                .replace("%amount%", amountStr)
                .replace("%target%", targetStr)
                .replace("%money%", moneyStr)
                .replace("%xp%", xpStr)
                .replace("%value%", valueStr);

        List<String> desc = new ArrayList<>(tpl.description().size());
        for (String line : tpl.description()) {
            desc.add(line
                    .replace("%amount%", amountStr)
                    .replace("%target%", targetStr)
                    .replace("%money%", moneyStr)
                    .replace("%xp%", xpStr)
                    .replace("%value%", valueStr));
        }
        return new SubstitutedStrings(display, desc);
    }

    private Contract rollContract(ContractTemplate t) {
        int amount = t.amountRange().roll();
        double money = t.moneyRange().roll();
        int xp = t.xpRange().roll();

        // v1.7.2 — delegate to shared helper so roll + reload paths stay in sync.
        SubstitutedStrings sub = substitutePlaceholders(t, amount, money, xp);

        return new Contract(t.id(), sub.displayName(), sub.description(),
                t.targetType(), t.targetValue(),
                amount, 0, money, xp, t.itemRewards(),
                t.iconMaterial(), t.iconCmd(), false);
    }

    // =====================================================================
    //  Catch Check
    // =====================================================================

    /**
     * Backward-compatible overload — calls {@link #checkCatch(Player, String, int, double)}
     * with {@code weight=0} (no weight-milestone contracts will match).
     * Kept so any external caller that hasn't been updated still works.
     */
    public void checkCatch(Player player, String fishId, int amount) {
        checkCatch(player, fishId, amount, 0.0);
    }

    /**
     * v1.7.1 — Weight-aware catch check. FishRewardHelper should call this
     * overload, passing the rolled fish weight (kg) so that
     * {@link TargetType#WEIGHT_MILESTONE} contracts can be evaluated.
     */
    public void checkCatch(Player player, String fishId, int amount, double weight) {
        if (!enabled || player == null || fishId == null) return;
        UUID uuid = player.getUniqueId();
        List<Contract> contracts = activeContracts.get(uuid);
        if (contracts == null || contracts.isEmpty()) return;

        int fishRarity = -1;
        if (plugin.getFishManager() != null) {
            CustomFish fish = plugin.getFishManager().getFishById(fishId);
            if (fish != null) fishRarity = fish.rarity();
        }

        boolean updated = false;
        for (int i = 0; i < contracts.size(); i++) {
            Contract c = contracts.get(i);
            if (c.isCompleted()) continue;
            if (!matchesContract(c.targetType(), c.targetValue(), fishId, fishRarity, weight)) continue;

            Contract advanced = c.withCatch(amount);
            contracts.set(i, advanced);
            updated = true;

            if (advanced.isCompleted()) {
                player.sendMessage(miniMessage.deserialize(
                        "<green><bold>✔ Contract Complete!</bold></green> <white>"
                                + advanced.displayName() + " <gray>— <yellow>open "
                                + "<gold>/pf contracts</gold> <yellow>to claim your reward."));
                player.playSound(player, org.bukkit.Sound.UI_TOAST_CHALLENGE_COMPLETE, 1.0f, 1.0f);
            } else {
                player.sendMessage(miniMessage.deserialize(
                        "<gray>Contract progress: <yellow>" + advanced.amountCaught()
                                + "/" + advanced.amountNeeded() + " <dark_gray>("
                                + advanced.displayName() + ")"));
            }
        }
        if (updated) dirty = true;
    }

    private boolean matchesContract(TargetType type, String value, String fishId,
                                    int fishRarity, double weight) {
        return switch (type) {
            case ANY -> true;
            case ANY_RARITY -> {
                int expected = rarityNameToValue(value);
                if (expected <= 0) yield false;
                yield fishRarity > 0 && fishRarity == expected;
            }
            case FISH_ID -> value.equalsIgnoreCase(fishId);
            case WEIGHT_MILESTONE -> {
                double threshold;
                try {
                    threshold = Double.parseDouble(value.trim());
                } catch (NumberFormatException e) {
                    yield false;
                }
                yield weight > 0 && weight >= threshold;
            }
        };
    }

    private int rarityNameToValue(String name) {
        if (name == null || name.isBlank()) return -1;
        return switch (name.toLowerCase(Locale.ROOT)) {
            case "common", "c", "1" -> 1;
            case "uncommon", "uc", "2" -> 2;
            case "rare", "r", "3" -> 3;
            case "epic", "e", "4" -> 4;
            case "legendary", "leg", "l", "5" -> 5;
            default -> -1;
        };
    }

